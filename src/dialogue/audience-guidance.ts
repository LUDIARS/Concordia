/**
 * 部署の「話し方」(spec/feature/departments.md §9.8、 2026-10-09 neco 指示) を、 起動時の前提データに
 * 足す節として組み立てる純関数。
 *
 * 非エンジニア向けはセッションの出力そのものを変える (後から LLM で言い換えない)。 言い換えると承認依頼や
 * `ask` マーカーの意味・形が崩れ、 「やったこと／決めてほしいこと」は作業している本人しか正確に書けないため。
 *
 * @implements SPEC-DEPT-AUDIENCE
 */

import type { DepartmentAudience } from "../departments/settings.js";

const NON_ENGINEER_GUIDANCE: readonly string[] = [
  "### 話し方: 非エンジニア向け",
  "この部署の依頼者はエンジニアではない。人に向けた返信は次のとおりに書く。",
  "- 日常の言葉で話す。専門用語が必要なら、その場で一言で言い換える。ファイル名・関数名・コマンドは、相手が見る必要があるときだけ添える。",
  "- 途中経過は今していることを一言で伝える。作業ログやコマンドの出力を並べない。",
  "- 人に決めてもらうときは「何を決めればよいか」と、推奨とその理由を短く書く。",
  "- 返信の最後に次の 3 項目を付ける。無い項目は「なし」と書く。",
  "  - やったこと",
  "  - 決めてほしいこと",
  "  - 残っていること",
  "- 完了・審査中・反映済み・まだ確かめていないことを分けて書く。確かめていないことを成功と書かない。",
  "- 選択肢の ask マーカーなど決まった形の出力は、形を崩さずに中の文だけを平易にする。",
  "- 平易に書くのは人に向けた言葉だけ。PR の説明・コミット・引き継ぎ資料は従来どおり技術的に書く。",
  "- 説明を簡単にすることを理由に、作業規則・承認・テストや公開の許可範囲を省かない。",
];

/** 前提データに足す節。 標準の話し方なら null (何も足さない)。 */
export function audienceGuidanceBlock(audience: DepartmentAudience): string | null {
  return audience === "non-engineer" ? NON_ENGINEER_GUIDANCE.join("\n") : null;
}
